// The editor declarations: `.sail/sail.d.ts` and `.sail/sail-intakes.d.ts`, through which an editor resolves `sail` and
// `sail/intakes` to this machine's sail. Each is a plain module that re-exports sail's own declarations by absolute
// path, so the `paths` of a repository's `.sail/tsconfig.json` name no machine. They are generated and ignored by git:
// `sail init` writes them, and `sail check` rewrites the ones that are missing or name another sail.
//
// `sail check` itself never reads them for its answer: it type-checks under its own `paths`, to the same files.
import { readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { SDK_TYPES } from './typecheck';

const HEADER = "// Generated by sail for this machine's editor. Not committed: sail check rewrites it.";

export interface EditorDeclaration {
  /** The file's name in `.sail/`. */
  name: string;
  text: string;
}

/** An editor declaration that couldn't be written. */
export class EditorWriteError extends Error {
  /** The file, absolute. */
  readonly path: string;

  // Written out, not implicit: Bun reads an implicit subclass constructor as uncovered.
  constructor(path: string, why: string) {
    super(why);
    this.name = 'EditorWriteError';
    this.path = path;
  }
}

/** A module that re-exports the declaration file `types`. The path is written as JSON, so any path is a specifier. */
const reexport = (types: string): string =>
  `${HEADER}\nexport * from ${JSON.stringify(types.replace(/\.d\.ts$/, ''))};\n`;

/** The two editor declarations, each re-exporting the file `SDK_TYPES` names for its module. */
export function editorDeclarations(): EditorDeclaration[] {
  return [
    { name: 'sail.d.ts', text: reexport(SDK_TYPES.sail[0] as string) },
    { name: 'sail-intakes.d.ts', text: reexport(SDK_TYPES['sail/intakes'][0] as string) },
  ];
}

/** What the file at `path` holds, or undefined when it can't be read. */
function current(path: string): string | undefined {
  try {
    return readFileSync(path, 'utf8');
  } catch {
    return undefined;
  }
}

/**
 * Writes the editor declarations that are missing from `sailDir` or differ from what they should hold, each to a
 * temporary name and then renamed, so an editor never reads half of one. Returns the files it wrote, absolute. One
 * that can't be written throws an `EditorWriteError`.
 */
export function writeEditorDeclarations(sailDir: string): string[] {
  const written: string[] = [];
  for (const { name, text } of editorDeclarations()) {
    const path = join(sailDir, name);
    if (current(path) === text) continue;
    const temporary = `${path}.${process.pid}.tmp`;
    try {
      writeFileSync(temporary, text);
      renameSync(temporary, path);
    } catch (error) {
      rmSync(temporary, { force: true });
      throw new EditorWriteError(path, error instanceof Error ? error.message : String(error));
    }
    written.push(path);
  }
  return written;
}
